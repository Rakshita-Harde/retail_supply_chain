--  Find products with unusually high quantity_received in a single day.
select product_id,date,quantity_received
from inventory i
where quantity_received >
      (
        select avg(quantity_received) 
        from inventory
        where product_id = i.product_id
      )
order by product_id, date; 

-- Identify days when quantity_sold was significantly higher than usual.
select product_id,date,quantity_sold
from inventory i
where quantity_sold >
      (
        select avg(quantity_sold) 
        from inventory
        where product_id = i.product_id
      )
order by product_id, date;

-- Calculate inventory turnover for each product.
select product_id,
    sum(quantity_sold) / avg(opening_stock) as inventory_turnover
from inventory
group by product_id;

--  Determine products with the highest month-wise inventory turnover.
