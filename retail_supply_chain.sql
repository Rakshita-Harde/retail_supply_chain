--  List all dates on which any product went into stock-out (closing_stock = 0).
select distinct date
from inventory
where closing_stock = 0
order by date;

--  Find the total number of stock-out events per product, ranked in descending order.
select product_id, count(*) as stock_out_events
from inventory
where closing_stock = 0
group by product_id
order by stock_out_events desc;

-- Identify warehouse–product combinations with the most frequent stock-outs.
select warehouse_id,product_id,count(*) as stock_out_count
from inventory
where closing_stock = 0
group by warehouse_id, product_id
order by stock_out_count desc;


-- Identify stock-outs occurring specifically on weekends.
select product_id,date,closing_stock
from inventory
where closing_stock = 0
  and dayofweek(date) in (1, 7)  
order by date;

--  Identify products that never went into stock-out.
select product_id,product_name
from products p
where product_id not in (
    select distinct product_id
    from inventory
    where closing_stock = 0
)
order by product_id;

--  Determine which warehouse had the highest count of stock-out events.
select warehouse_id,count(*) as stock_out_count
from inventory
where closing_stock = 0
group by warehouse_id
order by stock_out_count desc
limit 1;

-- Identify the day of the week with the highest stock-out frequency.
select dayofweek(date) as day_number,count(*) as stock_out_count
from inventory
where closing_stock = 0
group by dayofweek(date)
order by stock_out_count desc
limit 1;

-- Find products whose stock-out frequency increased month-over-month.
select product_id,month(date) as mnth,count(*) as stock_out_count
from inventory
where closing_stock = 0
group by product_id, yr, mnth;


